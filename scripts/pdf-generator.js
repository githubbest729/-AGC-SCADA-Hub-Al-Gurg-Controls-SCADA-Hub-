/* =========================================================
   AGC SCADA Hub — scripts/pdf-generator.js
   Uses the html2pdf.js CDN bundle (loaded in index.html) to
   turn the live "Requirements & Stakeholder Matrix" table into
   a branded "Requirements Specification" PDF for formal
   stakeholder sign-off. Runs entirely client-side.
   ========================================================= */

(function (global) {
  "use strict";

  const AGC = global.AGC = global.AGC || {};

  const COMPANY_NAME = "Al Gurg Automation and Controls";
  const COMPANY_ADDRESS = "Al Ittihad Road (Dubai-Sharjah Road), Al Khabisi Area, Deira, PO Box 25490, Dubai, UAE";

  /**
   * Builds a standalone, print-styled DOM node containing a
   * letterhead + the current Requirements table content, ready
   * to be rasterized by html2pdf.js. We build a detached clone
   * rather than printing the live page so the on-screen dark
   * theme doesn't bleed into the formal PDF.
   */
  function buildPrintableDocument(sourceTableEl, meta) {
    const wrapper = document.createElement("div");
    wrapper.id = "agc-pdf-export-root";
    wrapper.style.cssText = "font-family: Arial, Helvetica, sans-serif; color:#0f172a; background:#ffffff; padding:24px; width:780px;";

    const generatedOn = new Date().toLocaleString();
    const preparedBy = (meta && meta.preparedBy) || "AGC SCADA Hub";

    wrapper.innerHTML = `
      <div style="display:flex; justify-content:space-between; align-items:flex-start; border-bottom:3px solid #0284c7; padding-bottom:14px; margin-bottom:18px;">
        <div>
          <div style="font-size:20px; font-weight:800; color:#0f172a;">${COMPANY_NAME}</div>
          <div style="font-size:10.5px; color:#475569; margin-top:4px; max-width:420px;">${COMPANY_ADDRESS}</div>
        </div>
        <div style="text-align:right;">
          <div style="font-size:14px; font-weight:700; color:#0284c7;">REQUIREMENTS SPECIFICATION</div>
          <div style="font-size:10px; color:#475569; margin-top:4px;">Generated: ${generatedOn}</div>
          <div style="font-size:10px; color:#475569;">Prepared by: ${preparedBy}</div>
        </div>
      </div>
      <div id="agc-pdf-table-slot" style="margin-top:10px;"></div>
      <div style="margin-top:36px; display:flex; justify-content:space-between; gap:24px;">
        <div style="flex:1; border-top:1px solid #94a3b8; padding-top:6px; font-size:10.5px; color:#334155;">
          Client / Stakeholder Signature &amp; Date
        </div>
        <div style="flex:1; border-top:1px solid #94a3b8; padding-top:6px; font-size:10.5px; color:#334155;">
          AGC Project Engineer Signature &amp; Date
        </div>
      </div>
      <div style="margin-top:24px; font-size:9px; color:#94a3b8; text-align:center;">
        This document was generated by AGC SCADA Hub and reflects requirements logged as of the date above.
        Any changes after sign-off must be re-issued through a formal change request.
      </div>
    `;

    // Clone the live table and restyle it for a light, printable page
    const tableClone = sourceTableEl.cloneNode(true);
    tableClone.removeAttribute("id");
    tableClone.style.cssText = "width:100%; border-collapse:collapse; font-size:10.5px;";

    // Strip the trailing "actions" column (edit/delete buttons) — not relevant on paper
    stripActionsColumn(tableClone);

    // Re-style cells for a clean light-mode PDF regardless of the app's dark theme
    tableClone.querySelectorAll("th").forEach((th) => {
      th.style.cssText = "text-align:left; background:#0f172a; color:#ffffff; padding:6px 8px; font-size:9.5px; text-transform:uppercase; letter-spacing:0.4px;";
    });
    tableClone.querySelectorAll("td").forEach((td) => {
      td.style.cssText = "padding:6px 8px; border-bottom:1px solid #e2e8f0; color:#0f172a;";
    });
    tableClone.querySelectorAll("tr").forEach((tr, idx) => {
      if (idx % 2 === 1) tr.style.background = "#f8fafc";
    });
    // Flatten any status/priority badges to plain readable text/color
    tableClone.querySelectorAll(".badge").forEach((badge) => {
      badge.style.cssText = "display:inline-block; padding:2px 8px; border-radius:10px; font-size:9px; font-weight:700; background:#e2e8f0; color:#0f172a;";
    });

    wrapper.querySelector("#agc-pdf-table-slot").appendChild(tableClone);
    return wrapper;
  }

  function stripActionsColumn(table) {
    // Remove last <th> (blank actions header) and last <td> in every row
    const headRow = table.querySelector("thead tr");
    if (headRow && headRow.lastElementChild) headRow.removeChild(headRow.lastElementChild);
    table.querySelectorAll("tbody tr").forEach((tr) => {
      if (tr.lastElementChild) tr.removeChild(tr.lastElementChild);
    });
  }

  /**
   * Public entry point. Call from app.js:
   *   AGC.PDF.generateRequirementsPdf(document.getElementById('requirements-table'))
   */
  function generateRequirementsPdf(tableEl, options) {
    if (typeof html2pdf === "undefined") {
      alert("PDF engine failed to load. Please check your connection and try again once online (the PDF library is loaded from a CDN).");
      return;
    }
    if (!tableEl) {
      console.warn("AGC.PDF: no requirements table element provided.");
      return;
    }

    const meta = options || {};
    const printable = buildPrintableDocument(tableEl, meta);

    // Render off-screen so it doesn't flash on the live UI
    printable.style.position = "fixed";
    printable.style.left = "-10000px";
    printable.style.top = "0";
    document.body.appendChild(printable);

    const filename = `AGC-Requirements-Specification-${new Date().toISOString().slice(0, 10)}.pdf`;

    const opt = {
      margin: [10, 10, 10, 10],
      filename,
      image: { type: "jpeg", quality: 0.98 },
      html2canvas: { scale: 2, useCORS: true, backgroundColor: "#ffffff" },
      jsPDF: { unit: "mm", format: "a4", orientation: "landscape" },
      pagebreak: { mode: ["avoid-all", "css", "legacy"] }
    };

    html2pdf()
      .set(opt)
      .from(printable)
      .save()
      .catch((err) => {
        console.error("PDF generation failed:", err);
        alert("Could not generate the PDF. Please try again.");
      })
      .finally(() => {
        document.body.removeChild(printable);
      });
  }

  AGC.PDF = {
    generateRequirementsPdf
  };
})(window);
